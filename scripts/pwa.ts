import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import type { Plugin } from 'vite'

const publicAssets = [
  '/offline.html',
  '/offline-rhine.html',
  '/manifest.webmanifest',
  '/rhodes-island.svg',
  '/branding/rhodes-island.png',
  '/icons/rhodes-island-192.png',
  '/icons/rhodes-island-512.png',
  '/icons/rhodes-island-maskable-512.png',
  '/icons/rhodes-island-apple-180.png',
  '/manifest-rhine.webmanifest',
  '/branding/rhine-lab.png',
  '/icons/rhine-lab-192.png',
  '/icons/rhine-lab-512.png',
  '/icons/rhine-lab-maskable-512.png',
  '/icons/rhine-lab-180.png',
]

export async function writePwaWorker(directory: string): Promise<string> {
  const files = ['index.html', ...publicAssets.map((file) => file.slice(1))]
  const contents = await Promise.all(files.map((file) => readFile(path.join(directory, file))))
  const hash = createHash('sha256')
  for (let i = 0; i < files.length; i++) hash.update(files[i]).update(contents[i])
  const version = hash.digest('hex').slice(0, 16)
  const source = `// Generated by the PRTS build. Only public installation/offline assets are cached.
const CACHE_NAME = 'prts-public-${version}'
const PUBLIC_ASSETS = ${JSON.stringify(publicAssets)}
// This public presentation hint is never a preference source; online preferences come from SQLite.
const OFFLINE_THEME_KEY = '/__prts_public_offline_theme'
let themeWrites = Promise.resolve()
self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE_NAME).then((cache) => cache.addAll(
    PUBLIC_ASSETS.map((url) => new Request(url, { cache: 'reload', credentials: 'omit' }))
  )))
})
self.addEventListener('activate', (event) => {
  event.waitUntil(caches.keys().then((keys) => Promise.all(
    keys.filter((key) => key.startsWith('prts-public-') && key !== CACHE_NAME).map((key) => caches.delete(key))
  )).then(() => self.clients.claim()))
})
self.addEventListener('message', (event) => {
  if (event.data?.type === 'PRTS_ACTIVATE_UPDATE') self.skipWaiting()
  if (event.data?.type !== 'PRTS_THEME' || !['rhodes', 'rhine'].includes(event.data.theme) || typeof event.source?.id !== 'string') return
  const theme = event.data.theme
  const clientId = event.source.id
  themeWrites = themeWrites.catch(() => {}).then(async () => {
    const clients = await self.clients.matchAll({ type: 'window', includeUncontrolled: false })
    const client = clients.find((candidate) => candidate.id === clientId && candidate.type === 'window')
    if (!client) return
    try {
      const url = new URL(client.url)
      const scope = new URL(self.registration.scope)
      if (url.origin !== self.location.origin || !url.href.startsWith(scope.href)) return
    } catch { return }
    const cache = await caches.open(CACHE_NAME)
    await cache.put(OFFLINE_THEME_KEY, new Response(theme, { headers: { 'Content-Type': 'text/plain' } }))
  })
  event.waitUntil(themeWrites)
})
self.addEventListener('notificationclick', (event) => {
  if (!event.notification.tag.startsWith('prts-task-')) return
  event.notification.close()
  event.waitUntil(self.clients.matchAll({type:'window',includeUncontrolled:true}).then(async (clients) => {
    const client=clients.find((client)=>new URL(client.url).origin===self.location.origin)
    if (client) { await client.navigate('/#tasks');return client.focus() }
    return self.clients.openWindow('/#tasks')
  }))
})
self.addEventListener('fetch', (event) => {
  const request = event.request
  const url = new URL(request.url)
  if (request.method !== 'GET' || url.origin !== self.location.origin || url.pathname === '/api' || url.pathname.startsWith('/api/')) return
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(async () => {
      const cache = await caches.open(CACHE_NAME)
      const storedTheme = await cache.match(OFFLINE_THEME_KEY)
      const offlinePage = storedTheme && await storedTheme.text() === 'rhine' ? '/offline-rhine.html' : '/offline.html'
      return (await cache.match(offlinePage)) || (await cache.match('/offline.html')) || Response.error()
    }))
    return
  }
  if (PUBLIC_ASSETS.includes(url.pathname)) {
    event.respondWith(caches.open(CACHE_NAME).then(async (cache) => (await cache.match(url.pathname)) || fetch(request)))
  }
})
`
  await writeFile(path.join(directory, 'sw.js'), source)
  return version
}

export function prtsPwa(): Plugin {
  let directory: string
  return {
    name: 'prts-pwa',
    apply: 'build',
    configResolved(config) {
      directory = path.resolve(config.root, config.build.outDir)
    },
    async writeBundle() {
      await writePwaWorker(directory)
    },
  }
}
